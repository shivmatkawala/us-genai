# Data Types :-

    # Numeric:-
        # 1) Integer :- 
            # Any Number without decimal point is integer
            # Integeres can be +ve and -ve
            # including 0

            # Ex:-  20, 1, 2, 40, 0, -50, -1, -78

        # 2) Float:-  
            # Any Number with decimal point is float
            # Float can be +ve or -ve

            # Ex: 1.14, 0.000, -23.56, -0.123

        # 3) Complex:- A combination of Real number and Imaginary number.
            # Real Number :- All Ints and Floats
            # Imaginary Number:- A number with j prefix

            # Ex: 5+7j,  -12-45j, -0.56+4.5j


